import asyncio
import edge_tts
import os

TEXT = """
مرحباً بكم في نظام تري برو إي آر بي.
في هذا الدليل التدريبي السريع، سنتعلم معاً الطريقة الصحيحة والمحاسبية المعتمدة لإغلاق وردية الكاشير واستلام النقدية بدقة وأمان.
الخطوة الأولى: يقوم الكاشير بالضغط على زر إغلاق الوردية من أعلى شاشة الكاشير.
الخطوة الثانية: يفتح النظام نافذة الإغلاق الأعمى؛ وفيها يقوم الكاشير بعد النقدية الفعلية الموجودة في الدرج وتغذيتها فئة بفئة دون أن يرى مبيعات النظام مسبقاً، وذلك لمنع أي تلاعب أو شبهة خطأ.
الخطوة الثالثة: يدخل الكاشير إجمالي مبيعات بطاقات الدفع والفيزا ومحافظ إنستاباي من واقع إيصالات نقاط البيع البنكية.
الخطوة الرابعة: يقوم المشرف أو الكاشير المستلم بمراجعة العد الفعلي والتوقيع المشترك على استلام النقدية.
فور الضغط على تأكيد الإغلاق، يقوم النظام آلياً بتوليد قيد إقفال الوردية في الأستاذ العام، مع حصر أي عجز أو زيادة بدقة تامة.
شكراً لالتزامكم بمعايير الأمان المالي في تري برو إي آر بي.
"""

VOICE = "ar-EG-ShakirNeural"  # Professional Egyptian Arabic / MSA Voice

async def main():
    os.makedirs("tutorials", exist_ok=True)
    out_file = os.path.join("tutorials", "shift_closing_tutorial.mp3")
    print(f"Generating audio to {out_file}...")
    communicate = edge_tts.Communicate(TEXT, VOICE, rate="-4%")
    await communicate.save(out_file)
    print("Audio generated successfully!")

if __name__ == "__main__":
    asyncio.run(main())
